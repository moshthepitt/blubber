//! Deterministic Rust source generation, using no production or oracle helpers.

#![forbid(unsafe_code)]

use std::fmt::Write;

const NUMBERS: [&str; 10] = [
    "u8", "u16", "u32", "u64", "u128", "i8", "i16", "i32", "i64", "i128",
];
const KEYS: [&str; 8] = ["u16", "i16", "u32", "i32", "u8", "i8", "[u8; 3]", "Pubkey"];

fn structure(out: &mut String, name: &str, fields: &[(&str, String)], account: bool) {
    writeln!(
        out,
        "#[blubber::schema{}]",
        if account { "(account)" } else { "" }
    )
    .unwrap();
    writeln!(out, "struct {name} {{").unwrap();
    for (field, ty) in fields {
        writeln!(out, "    {field}: {ty},").unwrap();
    }
    writeln!(out, "}}\nimpl Bridge for {name} {{").unwrap();
    writeln!(
        out,
        "fn schema() -> ModelSchema {{ ModelSchema::Struct(vec!["
    )
    .unwrap();
    for (_, ty) in fields {
        writeln!(out, "<{ty} as Bridge>::schema(),").unwrap();
    }
    writeln!(out, "]) }}").unwrap();
    writeln!(out, "fn owned(value: &Value) -> Self::Owned {{ let Value::Struct(fields) = value else {{ panic!(\"struct value\") }}; {name}Owned {{").unwrap();
    for (i, (field, ty)) in fields.iter().enumerate() {
        writeln!(out, "{field}: <{ty} as Bridge>::owned(&fields[{i}]),").unwrap();
    }
    writeln!(
        out,
        "}} }}\nfn value(value: Self::Owned) -> Value {{ Value::Struct(vec!["
    )
    .unwrap();
    for (field, ty) in fields {
        writeln!(out, "<{ty} as Bridge>::value(value.{field}),").unwrap();
    }
    writeln!(out, "]) }}").unwrap();
    writeln!(
        out,
        "fn value_from_read(value: Self::Read<'_>) -> Value {{ Value::Struct(vec!["
    )
    .unwrap();
    for (field, ty) in fields {
        writeln!(
            out,
            "<{ty} as Bridge>::value_from_read(value.try_{field}().unwrap()),"
        )
        .unwrap();
    }
    writeln!(out, "]) }}").unwrap();
    writeln!(
        out,
        "fn snapshot(handle: &Self::Mut<'_>) -> blubber::Result<Value> {{ Ok(Value::Struct(vec!["
    )
    .unwrap();
    for (field, ty) in fields {
        writeln!(
            out,
            "<{ty} as Bridge>::value_from_read(handle.try_{field}()?),"
        )
        .unwrap();
    }
    writeln!(out, "])) }}").unwrap();
    writeln!(
        out,
        "fn loan<'s>(handle: &'s mut Self::Mut<'_>) -> Self::Mut<'s> {{ handle.reborrow() }}"
    )
    .unwrap();
    writeln!(out, "fn api(mut handle: Self::Mut<'_>, path: &[Segment], edit: &blubber_model::ApiEdit, calls: &mut blubber_model::Callbacks, destination: &mut Option<Vec<u8>>) -> blubber::Result<blubber_model::ApiReturn> {{ let (Segment::Field(field), rest) = path.split_first().expect(\"field path\") else {{ panic!(\"field selection\") }}; match field {{").unwrap();
    for (i, (field, ty)) in fields.iter().enumerate() {
        writeln!(
            out,
            "{i} => <{ty} as Bridge>::api(handle.{field}_mut(), rest, edit, calls, destination),"
        )
        .unwrap();
    }
    writeln!(out, "_ => panic!(\"field ordinal\"), }} }}").unwrap();
    writeln!(out, "fn removed(value: Option<Self::Removed>) -> Observed {{ Observed::Present(value.is_some()) }}").unwrap();
    writeln!(out, "fn borrowed<'a>(value: &'a Value, arena: &'a bumpalo::Bump) -> Self::Init<'a> {{ let Value::Struct(fields) = value else {{ panic!(\"struct input\") }}; {name}Init {{").unwrap();
    for (i, (field, ty)) in fields.iter().enumerate() {
        writeln!(
            out,
            "{field}: <{ty} as Bridge>::borrowed(&fields[{i}], arena),"
        )
        .unwrap();
    }
    writeln!(out, "}} }}").unwrap();
    writeln!(out, "fn apply(mut handle: Self::Mut<'_>, path: &[Segment], edit: &ModelEdit) -> blubber::Result<Observed> {{ let (Segment::Field(field), rest) = path.split_first().expect(\"field path\") else {{ panic!(\"field selection\") }}; match field {{").unwrap();
    for (i, (field, ty)) in fields.iter().enumerate() {
        writeln!(
            out,
            "{i} => <{ty} as Bridge>::apply(handle.{field}_mut(), rest, edit),"
        )
        .unwrap();
    }
    writeln!(out, "_ => panic!(\"field ordinal\"), }} }} }}").unwrap();
}

pub(crate) fn source() -> String {
    let mut out = String::from("// Generated by tests/support/differential/generate.rs.\n");
    for id in 0..32 {
        writeln!(
            out,
            "mod fixture_{id:02} {{\n#![forbid(unsafe_code)]\nuse super::*;"
        )
        .unwrap();
        let number = NUMBERS[id % NUMBERS.len()];
        let key = KEYS[id / 4];
        let body = match id % 8 {
            0 => {
                structure(
                    &mut out,
                    "Packed",
                    &[
                        ("flag", "bool".into()),
                        ("number", number.into()),
                        ("raw", format!("[u8; {}]", id + 1)),
                    ],
                    false,
                );
                "Packed".into()
            }
            1 => format!("List<{number}>"),
            2 => "List<Str>".into(),
            3 => format!("Map<{key}, {number}>"),
            4 => format!("Map<{key}, Str>"),
            5 | 7 => {
                let deep = id % 8 == 7;
                structure(
                    &mut out,
                    "Item",
                    &[
                        ("text", "Str".into()),
                        (
                            "values",
                            if deep {
                                format!("List<List<{number}>>")
                            } else {
                                format!("List<{number}>")
                            },
                        ),
                        (
                            "maybe",
                            if deep {
                                "Option<Option<Str>>".into()
                            } else {
                                "Option<Str>".into()
                            },
                        ),
                        ("flag", "bool".into()),
                    ],
                    false,
                );
                if deep {
                    format!("List<Map<{key}, List<Item>>>")
                } else {
                    "List<Item>".into()
                }
            }
            6 => format!("Map<{key}, List<Option<Str>>>"),
            _ => unreachable!(),
        };
        structure(
            &mut out,
            "Root",
            &[
                ("left", "Str".into()),
                ("stamp", number.into()),
                ("body", body),
                ("right", "List<u8>".into()),
                ("optional", "Option<Str>".into()),
                ("fixed", format!("[u8; {}]", id + 1)),
            ],
            true,
        );
        writeln!(
            out,
            "pub(super) fn shape() -> ModelSchema {{ <Root as Bridge>::schema() }}"
        )
        .unwrap();
        if id == 0 {
            writeln!(out, "#[test]\nfn detection_controls() {{ detection_controls_for::<Root>(Root::DISCRIMINATOR); }}").unwrap();
        }
        writeln!(
            out,
            "#[test]\nfn histories() {{ run_fixture::<Root>({id}, Root::DISCRIMINATOR); }}\n}}"
        )
        .unwrap();
    }
    writeln!(out, "#[test]\nfn fixture_inventory() {{ let schemas = [").unwrap();
    for id in 0..32 {
        writeln!(out, "fixture_{id:02}::shape(),").unwrap();
    }
    writeln!(out, "]; let unique: std::collections::BTreeSet<_> = schemas.iter().map(|s| format!(\"{{s:?}}\")).collect(); assert_eq!(unique.len(), 32); assert_eq!(schemas.iter().map(oracle::depth).max(), Some(8)); for s in schemas {{ s.check(8).unwrap(); }} }}").unwrap();
    out
}
