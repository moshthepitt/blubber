//! SDK-independent account identity, sizing and copied constraint metadata.

use crate::{Error, ErrorKind, Result, RootSchema, View};

/// Largest native copied constraint prefix emitted for an account schema.
///
/// The 1,024-byte cap includes native padding. SBF v0/v3 acceptance fixtures
/// exercise loading, passing and refreshing prefixes at this limit. Disable
/// copying with `#[blubber::schema(account, constraint_fields = false)]` for
/// wider accounts; their fields remain available through checked readers.
pub const MAX_CONSTRAINT_PREFIX_SIZE: usize = 1024;

/// Account identity and copied fixed fields, generated by `schema(account)`.
///
/// This trait needs neither an SDK nor allocation. [`crate::Schema::Init`]
/// supplies the borrowed initializer; [`RootSchema`] supplies the checked root
/// table. Native adapters authenticate the owner separately.
pub trait AccountSchema: RootSchema {
    /// The eight wire bytes identifying this account schema.
    const DISCRIMINATOR: [u8; 8];
    /// An explicit override, or `None` for the D21 layout-bound SHA-256 identity.
    const DISCRIMINATOR_OVERRIDE: Option<[u8; 8]>;
    /// Stable application namespace, defaulting to the literal `account:<Name>`.
    const NAMESPACE: &'static str;
    /// Application semantic epoch; layout changes are detected independently.
    const SEMANTIC_EPOCH: u32;
    /// Version-one canonical descriptor bytes, computed at compile time.
    const WIRE_DESCRIPTOR_BYTES: &'static [u8];
    /// Smallest account encoding, including its twelve-byte envelope.
    const MIN_ACCOUNT_LEN: u32;
    /// Owned copies of fixed fields, with the declaration's field visibility.
    ///
    /// Variable fields have no corresponding field. An opted-out account has
    /// the empty prefix `()`. The prefix never borrows serialized storage.
    type Prefix: Copy;

    /// Copies fixed fields from an exact root region, checking their domains.
    ///
    /// The supplied region is interpreted using this schema's descriptor and
    /// retains its account-relative error base. This does not validate variable
    /// children or authenticate an envelope or owner. Adapters authenticate
    /// owner, schema identity and envelope before publishing the prefix. Lazy
    /// adapters rely on approved writer history for variable children; checked
    /// adapters additionally validate the complete root before constraints.
    fn read_prefix(view: View<'_>) -> Result<Self::Prefix>;

    /// Constructs a root reader from a checked envelope under a valid-history obligation.
    ///
    /// SDK callers authenticate owner and exclusion separately. With
    /// `verify-on-load` or `checked = true`, this also scans the root. The hook
    /// retains root origin for generated `verify()`; bare subtree reads lack it.
    #[doc(hidden)]
    fn __read_account(bytes: &[u8], checked: bool) -> Result<Self::Read<'_>>;

    /// Adds reservation to the minimum account encoding, without an initializer.
    ///
    /// Returns `ArithmeticOverflow` when the sum cannot fit the format's `u32`
    /// length. Runtime allocation and creation limits are checked by the SDK
    /// adapter. The `usize` result can be used in account space constraints.
    fn space(reserve: usize) -> Result<usize> {
        account_space(Self::MIN_ACCOUNT_LEN, reserve)
    }
}

pub(crate) const fn account_space(minimum: u32, reserve: usize) -> Result<usize> {
    match (minimum as usize).checked_add(reserve) {
        Some(size) if size <= u32::MAX as usize => Ok(size),
        _ => Err(Error::new(ErrorKind::ArithmeticOverflow, Error::NO_OFFSET)),
    }
}

/// Selects a generated field at compile time, including through type aliases.
#[doc(hidden)]
pub struct PrefixChoice<const FIXED: bool>;

/// Selects a named copied field or its tail without evaluating skipped reads.
#[doc(hidden)]
pub trait SelectPrefix<Field: Copy, Tail: Copy> {
    type Output: Copy;
    fn select(tail: Tail, field: impl FnOnce(Tail) -> Result<Field>) -> Result<Self::Output>;
}

impl<Field: Copy, Tail: Copy> SelectPrefix<Field, Tail> for PrefixChoice<true> {
    type Output = Field;
    #[inline(always)]
    fn select(tail: Tail, field: impl FnOnce(Tail) -> Result<Field>) -> Result<Field> {
        field(tail)
    }
}

impl<Field: Copy, Tail: Copy> SelectPrefix<Field, Tail> for PrefixChoice<false> {
    type Output = Tail;
    #[inline(always)]
    fn select(tail: Tail, _: impl FnOnce(Tail) -> Result<Field>) -> Result<Tail> {
        Ok(tail)
    }
}
